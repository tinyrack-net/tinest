/// A plugin registration returned invalid data from its effect-free `define`
/// handler.
final class PluginRegistrationException extends FormatException {
  /// Creates a registration validation failure.
  const new(super.message, {this.path});

  /// Stable field path within the registration document.
  final String? path;
}

/// Lifecycle transitions that an extension plugin may observe.
enum PluginLifecycle {
  /// An Agent definition became attached to a session.
  agentAttach('agent_attach'),

  /// An Agent definition was detached from a session.
  agentDetach('agent_detach'),

  /// A session was opened.
  sessionOpen('session_open'),

  /// A session is about to close.
  sessionClose('session_close'),

  /// A user turn is about to begin.
  beforeTurn('before_turn'),

  /// A model request is about to begin.
  beforeModel('before_model'),

  /// A model request finished.
  afterModel('after_model'),

  /// A tool invocation is about to begin.
  beforeTool('before_tool'),

  /// A tool invocation finished.
  afterTool('after_tool'),

  /// A turn finished.
  afterTurn('after_turn'),

  /// The owning operation was cancelled.
  cancel('cancel'),

  /// A lifecycle transition failed.
  error('error'),

  /// A durable scheduled handler became due.
  scheduled('scheduled'),

  /// The user activated a declarative UI action.
  uiAction('ui_action');

  new(this.wireName);

  /// Stable Lua registration key.
  final String wireName;
}

/// SDK-owned kinds of executable contribution binding.
enum PluginHandlerKind {
  /// Agent driver callback.
  driver('driver'),

  /// Model-visible tool callback.
  tool('tool'),

  /// Revision-bound callback used by dynamically materialized tools.
  toolTemplate('tool_template'),

  /// Lifecycle callback.
  hook('hook'),

  /// Session-control normalization callback.
  sessionControl('session_control'),

  /// Declarative UI renderer callback.
  ui('ui'),

  /// Declarative UI action callback.
  action('action');

  new(this.wireName);

  /// Stable SDK wire name.
  final String wireName;
}

/// Revision-local opaque identity of a Lua closure exported by the SDK.
///
/// Plugin authors never provide [internalKey]. It is accepted only when it is
/// the deterministic key for the contribution kind, lifecycle, and local ID.
final class PluginHandlerBinding {
  /// Creates one already-validated internal handler binding.
  const new({
    required this.pluginId,
    required this.executionRevisionHash,
    required this.kind,
    required this.localId,
    required this.internalKey,
    this.lifecycle,
  });

  /// Plugin revision that created this binding.
  final String pluginId;

  /// Exact composite execution revision that created this binding.
  final String executionRevisionHash;

  /// Contribution kind owning the closure.
  final PluginHandlerKind kind;

  /// Plugin-local contribution ID.
  final String localId;

  /// Runtime-only named-handler key generated by the SDK.
  final String internalKey;

  /// Lifecycle encoded into hook and action keys.
  final PluginLifecycle? lifecycle;

  @override
  String toString() => internalKey;
}

/// One registered Agent driver.
final class PluginDriverRegistration {
  /// Creates validated driver metadata.
  const new({
    required this.id,
    required this.binding,
    required this.requiredCapabilities,
    required this.declaredOperations,
    required this.requiredModelCapabilities,
    required this.metadata,
  });

  /// Globally qualified contribution ID.
  final String id;

  /// SDK-owned closure binding.
  final PluginHandlerBinding binding;

  /// Host capabilities needed by this driver.
  final Set<String> requiredCapabilities;

  /// Exact SDK primitive operations referenced by this contribution's `uses`.
  final Set<String> declaredOperations;

  /// Provider-neutral model features required by the harness.
  final Set<String> requiredModelCapabilities;

  /// JSON presentation or driver-specific metadata.
  final Map<String, Object?> metadata;
}

/// One independently selectable Lua tool contribution.
final class PluginToolRegistration {
  /// Creates validated tool metadata.
  const new({
    required this.id,
    required this.name,
    required this.description,
    required this.binding,
    required this.kind,
    required this.inputSchema,
    required this.outputSchema,
    required this.payloadSchema,
    required this.effects,
    required this.requiredCapabilities,
    required this.declaredOperations,
    required this.presentation,
  });

  /// Globally qualified contribution ID.
  final String id;

  /// Exact model-visible wire name. Human labels belong in [presentation].
  final String name;

  /// Human-readable behavior summary.
  final String description;

  /// SDK-owned closure binding.
  final PluginHandlerBinding binding;

  /// `function`, `deferred`, or non-visible `template`.
  final String kind;

  /// Provider-neutral JSON input schema.
  final Map<String, Object?> inputSchema;

  /// Optional provider-neutral JSON output schema.
  final Map<String, Object?>? outputSchema;

  /// Validated cross-VM payload schema for a dynamic template.
  final Map<String, Object?>? payloadSchema;

  /// Declared effects. The capability broker may raise their effective risk.
  final Set<String> effects;

  /// Host capabilities needed by this tool.
  final Set<String> requiredCapabilities;

  /// Exact SDK primitive operations referenced by this contribution's `uses`.
  final Set<String> declaredOperations;

  /// Declarative presentation metadata.
  final Map<String, Object?> presentation;
}

/// One ordered lifecycle handler contribution.
final class PluginHookRegistration {
  /// Creates validated lifecycle hook metadata.
  const new({
    required this.id,
    required this.lifecycle,
    required this.binding,
    required this.requiredCapabilities,
    required this.declaredOperations,
    required this.payloadSchema,
    required this.metadata,
  });

  /// Globally qualified contribution ID.
  final String id;

  /// Transition observed by this hook.
  final PluginLifecycle lifecycle;

  /// SDK-owned closure binding.
  final PluginHandlerBinding binding;

  /// Host capabilities needed by this hook.
  final Set<String> requiredCapabilities;

  /// Exact SDK primitive operations referenced by this contribution's `uses`.
  final Set<String> declaredOperations;

  /// Validated callback payload for a UI action or scheduled handler.
  ///
  /// Ordinary lifecycle hooks receive their lifecycle context and leave this
  /// unset. Action refs and durable scheduled handlers receive only data
  /// matching this schema.
  final Map<String, Object?>? payloadSchema;

  /// JSON metadata passed to the driver.
  final Map<String, Object?> metadata;
}

